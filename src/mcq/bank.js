export async function loadExtra(t) {
  try {
    const res = await fetch(`/mcq/${t}.json`);
    if (!res.ok || !(res.headers.get('content-type') || '').includes('json')) return [];
    return (await res.json()).map((s) => { const p = s.split('|'); return [p[0], p.slice(1, 5), +p[5], p[6]]; });
  } catch (e) { return []; }
}
